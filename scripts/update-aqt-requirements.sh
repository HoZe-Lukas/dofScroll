# Regenerates packaging/ci/aqt-requirements.txt: aqtinstall (AQT_VERSION of packaging/qt.env) and all
# of its dependencies, pinned by version AND SHA-256, for `pip install --require-hashes`. aqtinstall
# downloads Qt, which the released packages bundle, so the tool itself must not be replaceable.
# The hashes are those that PyPI lists for every file of each pinned version (wheels of all
# platforms and the sdist), so the same file works on Linux, Windows and macOS and on any Python.
# Needs network access (PyPI) and python3 with venv. Run it whenever AQT_VERSION changes, review the
# diff, commit it; scripts/check-ci-pins.sh fails when file and qt.env disagree.
# Usage: scripts/update-aqt-requirements.sh
set -eu
cd "$(dirname "$0")/.."
. packaging/qt.env
out=packaging/ci/aqt-requirements.txt
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

python3 -m venv "$tmp/venv"
"$tmp/venv/bin/pip" install --quiet "aqtinstall==${AQT_VERSION}"
"$tmp/venv/bin/pip" freeze --all | grep -v -i -E '^(pip|setuptools|wheel)==' > "$tmp/pins.txt"
grep -q -i "^aqtinstall==${AQT_VERSION}\$" "$tmp/pins.txt"

python3 -I - "$tmp/pins.txt" "$out" "$AQT_VERSION" <<'PY'
import json, sys, urllib.request
pins_file, out, aqt = sys.argv[1:4]
lines = [
    "# SPDX-License-Identifier: GPL-3.0-or-later",
    "# SPDX-FileCopyrightText: 2026 Lukas Hois-Zelinka",
    "#",
    f"# aqtinstall {aqt} (AQT_VERSION in packaging/qt.env) and its dependencies, pinned by SHA-256.",
    "# Generated by scripts/update-aqt-requirements.sh, do not edit by hand. Install with:",
    "#   pip install --require-hashes --no-deps -r packaging/ci/aqt-requirements.txt",
    "# Every file PyPI lists for a version is allowed, so one file serves all platforms and Pythons.",
]
for line in open(pins_file):
    name, _, ver = line.strip().partition("==")
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{ver}/json", timeout=60) as r:
        files = json.load(r)["urls"]
    hashes = sorted({f["digests"]["sha256"] for f in files})
    if not hashes:
        sys.exit(f"no files on PyPI for {name}=={ver}")
    lines.append(f"{name.lower()}=={ver} \\")
    lines.append(" \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
open(out, "w").write("\n".join(lines) + "\n")
PY
echo "wrote $out ($(grep -c '==' "$out") packages)"
